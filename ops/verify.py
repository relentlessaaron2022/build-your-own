#!/usr/bin/env python3
"""Step 4: Verify. Nothing is done until this script says so.
Usage: python3 ops/verify.py [TASK_ID ...]   (no args = check all)
Updates tasks.json statuses and regenerates PLAN.md."""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
STATE = ROOT / "tasks.json"

BANNED_NAME = ["trump"]
BANNED_WORDS = [
    "accordingly","additionally","consequently","hence","however","indeed","moreover",
    "nevertheless","nonetheless","notwithstanding","thus","undoubtedly",
    "adept","commendable","dynamic","efficient","ever-evolving","exciting","exemplary",
    "innovative","invaluable","robust","seamless","synergistic","thought-provoking",
    "transformative","utmost","vibrant","vital",
    "landscape","realm","tapestry","optimization","synergy",
    "delve","delves","embark","facilitate","maximize","underscore","underscores","utilize","augment",
]
BANNED_PHRASES = [
    "a testament to","in conclusion","in summary","it's important to note","it is important to note",
    "it's worth noting","it is worth noting","on the contrary","this is not an exhaustive list",
    "game-changer","in today's fast-paced",
]

def check(task):
    errs = []
    p = ROOT / task["output"]
    if not p.exists():
        return ["missing output " + task["output"]]
    text = p.read_text(encoding="utf-8")
    low = text.lower()
    words = len(re.findall(r"\b[\w'-]+\b", text))
    if words < task["min_words"]:
        errs.append(f"word count {words} < {task['min_words']}")
    for s in task["sections"]:
        if not re.search(r"^#{1,4}\s.*" + re.escape(s), text, re.M | re.I):
            errs.append(f"missing section heading: {s}")
    for w in BANNED_NAME + BANNED_WORDS:
        hits = re.findall(r"\b" + re.escape(w) + r"\b", low)
        if hits:
            errs.append(f"banned word '{w}' x{len(hits)}")
    for ph in BANNED_PHRASES:
        if ph in low:
            errs.append(f"banned phrase '{ph}'")
    return errs

def render_plan(state):
    rows = ["# PLAN — shared state (generated by verify.py; edit tasks.json, not this file)\n",
            f"Wave {state['wave']}\n", "| ID | Agenda | Task | Status | Output | Last check |",
            "|----|--------|------|--------|--------|------------|"]
    for t in state["tasks"]:
        rows.append(f"| {t['id']} | {t['agenda']} | {t['title']} | **{t['status']}** | `{t['output']}` | {t.get('last_check','-')} |")
    (ROOT / "PLAN.md").write_text("\n".join(rows) + "\n", encoding="utf-8")

def main():
    state = json.loads(STATE.read_text())
    want = set(sys.argv[1:])
    failed = 0
    for t in state["tasks"]:
        if want and t["id"] not in want:
            continue
        errs = check(t)
        if errs:
            failed += 1
            if (ROOT / t["output"]).exists():
                t["status"] = "failed-verify"
            t["last_check"] = "; ".join(errs)[:300]
            print(f"FAIL {t['id']}: " + "; ".join(errs))
        else:
            t["status"] = "done"
            t["last_check"] = "pass"
            print(f"PASS {t['id']}")
    STATE.write_text(json.dumps(state, indent=2) + "\n")
    render_plan(state)
    sys.exit(1 if failed else 0)

if __name__ == "__main__":
    main()
